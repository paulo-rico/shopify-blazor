namespace Shopify.Blazor.Cli;

/// <summary>
/// The Razor source <c>add page</c> writes.
/// </summary>
/// <remarks>
/// The template is deliberately opinionated about the three states, because their absence is the
/// silent failure the toolkit is built to prevent: a page that never sets a loading flag, has no
/// empty branch and swallows its exception renders perfectly and tells the developer nothing.
/// It is equally opinionated about <c>@rendermode InteractiveServer</c> — without it every control
/// on the page renders and does nothing (see docs/adr/0001-hosting-model.md).
/// </remarks>
public static class PageTemplate
{
    /// <summary>The render mode every page in this toolkit must state.</summary>
    public const string RenderModeDirective = "@rendermode InteractiveServer";

    /// <summary>The route for a page named <paramref name="name"/>, including the leading slash.</summary>
    public static string Route(string name) => "/" + NameHelper.ToKebabCase(name);

    /// <summary>The class and file name for a page named <paramref name="name"/>.</summary>
    public static string ClassName(string name) => NameHelper.ToPascalCase(name);

    /// <summary>Renders the page's Razor source.</summary>
    public static string Render(string name)
    {
        var className = ClassName(name);
        var route = Route(name);

        return $$"""
            @page "{{route}}"
            {{RenderModeDirective}}
            @* Interactive Server on purpose: docs/adr/0001-hosting-model.md. A Blazor Web App is
               static without this, so the markup below renders and every handler is never attached. *@
            @* Every namespace this file needs is named here, never left to the project's
               _Imports.razor or to enclosing-namespace lookup: a generated project whose root
               namespace differs from the toolkit's would otherwise fail to compile on a type it
               cannot see, while this repository builds perfectly. *@
            @using Polaris.Blazor.Events
            @using Shopify.Blazor.AppBridge
            @inject IAppBridgeInterop Bridge

            @*
                {{className}} — generated by `shopify-blazor add page {{className}}`.

                The four branches below are the whole point: loading, error, empty and content. Keep
                them. A page that silently renders nothing when the data is missing is the failure
                this shape exists to prevent, and `shopify-blazor doctor` looks for the same rules.
            *@
            <PolarisPage Heading="{{className}}">
                <PolarisStack Gap="PolarisGap.Base">
                    <PolarisSection>
                        <PolarisStack Direction="PolarisStackDirection.Inline" Gap="PolarisGap.Base">
                            <PolarisButton Variant="PolarisButtonVariant.Primary"
                                           OnClick="LoadAsync"
                                           Loading="_loading">
                                Refresh
                            </PolarisButton>
                        </PolarisStack>
                    </PolarisSection>

                    @if (_loading)
                    {
                        @* Loading: say what is loading, and keep the spinner's label for a screen reader. *@
                        <PolarisSection>
                            <PolarisStack Direction="PolarisStackDirection.Inline" Gap="PolarisGap.Base">
                                <PolarisSpinner AccessibilityLabel="Loading {{className}}" />
                                <PolarisText>Loading {{className}}…</PolarisText>
                            </PolarisStack>
                        </PolarisSection>
                    }
                    else if (_error is not null)
                    {
                        @* Error: the message a person can act on, not just "something went wrong". *@
                        <PolarisSection>
                            <PolarisBanner Heading="Could not load {{className}}" Tone="PolarisTone.Critical">
                                <PolarisText Paragraph="true">@_error</PolarisText>
                            </PolarisBanner>
                        </PolarisSection>
                    }
                    else if (_items is null || _items.Count == 0)
                    {
                        @* Empty: rendered conditionally, because an empty state cannot detect
                           emptiness on its own and would sit beside a full table. *@
                        <PolarisSection>
                            <PolarisEmptyState Heading="Nothing here yet">
                                <PolarisText Slot="subheading">
                                    Once there is something to show, it will appear here.
                                </PolarisText>
                            </PolarisEmptyState>
                        </PolarisSection>
                    }
                    else
                    {
                        <PolarisSection>
                            @foreach (var item in _items)
                            {
                                <PolarisText>@item</PolarisText>
                            }
                        </PolarisSection>
                    }
                </PolarisStack>
            </PolarisPage>

            @code {
                private bool _loading;
                private string? _error;
                private IReadOnlyList<string>? _items;

                // One handler overload only. A parameterless LoadAsync beside this one makes
                // OnClick="LoadAsync" ambiguous between Func<Task> and Func<T, Task>, which is a
                // Razor compile error rather than a silent failure — but it makes every generated
                // page fail to build, so it is worth being explicit about.
                private async Task LoadAsync(PolarisEventArgs args)
                {
                    await ReloadAsync();
                }

                // TODO: replace the stub with a real call. The server owns the Shopify credentials,
                // so the browser asks this app's own endpoint and the app talks to the Admin API:
                //
                //     var result = await Bridge.WithLoadingAsync(
                //         () => Bridge.FetchAsync<MyResponse>("/api/{{route.TrimStart('/')}}").AsTask());
                //
                // See Components/Pages/Products.razor in the sample app for the full shape,
                // including how a rejected session token is explained.
                private async Task ReloadAsync()
                {
                    if (_loading)
                    {
                        return;
                    }

                    _loading = true;
                    _error = null;

                    try
                    {
                        await Task.Yield();
                        _items = [];
                    }
                    catch (Exception ex)
                    {
                        // Assign the message. An exception that is swallowed is indistinguishable
                        // from an empty result, and the empty state will lie about it.
                        _error = ex.Message;
                    }
                    finally
                    {
                        _loading = false;
                    }
                }
            }
            """;
    }
}
