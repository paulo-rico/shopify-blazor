#!/usr/bin/env python3
"""Writes docs/source-summaries.md — one table per directory, pointing at each source's summary.

The summaries themselves live beside their sources, which is right for reading one file and useless
for finding the file you want. This index is the map: every source under `src/`, grouped by project
and directory, with the first sentence of its summary. It is also the cheapest way to get an agent
oriented in one screenful of context.

The purpose line is the summary's first paragraph after its `#` heading, cut at the first sentence, so
a summary has to open with a sentence that stands on its own.

Usage:
    python3 tools/generate-summary-index.py            # rewrite docs/source-summaries.md
    python3 tools/generate-summary-index.py --check    # exit 1 when the committed index is stale
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "docs" / "source-summaries.md"
ROOTS = ["src"]

SOURCE_SUFFIXES = {".cs", ".razor", ".js", ".css"}
SKIPPED_DIRECTORIES = {"bin", "obj", "node_modules", ".git", ".vs", ".nuget", "artifacts"}
MAX_PURPOSE = 200

HEADER = """# Source summaries

<!-- Generated by tools/generate-summary-index.py. Do not edit by hand. -->

Every source file under `src/` has a sibling `<name>.md` — `PolarisButton.cs.md` beside
`PolarisButton.cs` — holding its API and its behaviour in prose, so that a file can be understood
without reading it. **Read the summary first.** The naming rule, the format, and what to do when a
summary is stale are in [`AGENTS.md`](../AGENTS.md#source-summaries-read-these-instead-of-the-source).

`python3 tools/check-summaries.py` reports a summary that is missing or older than its source.
"""


def is_skipped(path: Path) -> bool:
    return bool(set(path.parts) & SKIPPED_DIRECTORIES)


def sources() -> list[Path]:
    found: list[Path] = []
    for name in ROOTS:
        for candidate in (ROOT / name).rglob("*"):
            if candidate.is_file() and candidate.suffix.lower() in SOURCE_SUFFIXES and not is_skipped(candidate):
                found.append(candidate)
    return sorted(found, key=lambda p: str(p).lower())


def purpose_of(summary: Path) -> str:
    """The first sentence of the first paragraph after the heading, flattened to one line."""
    if not summary.exists():
        return "*no summary yet*"

    lines = summary.read_text(encoding="utf-8", errors="replace").splitlines()
    paragraph: list[str] = []
    started = False

    for line in lines:
        stripped = line.strip()
        if not started:
            # Skip the marker comments and the `#` heading, then start at the first non-empty line.
            if stripped.startswith("#") or stripped.startswith("<!--") or not stripped:
                continue
            started = True
        if stripped.startswith("#") and paragraph:
            break
        if not stripped:
            if paragraph:
                break
            continue
        paragraph.append(stripped)

    text = " ".join(paragraph)
    text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)  # links -> their label
    text = re.sub(r"[`*_]", "", text)
    text = re.sub(r"\s+", " ", text).strip()

    cut = re.search(r"(?<=[.!?])\s", text)
    if cut:
        text = text[: cut.start()]

    if len(text) > MAX_PURPOSE:
        text = text[: MAX_PURPOSE - 1].rsplit(" ", 1)[0] + "…"

    return text or "*no description*"


def render() -> str:
    groups: dict[str, list[Path]] = {}
    for source in sources():
        relative = source.relative_to(ROOT)
        groups.setdefault(str(relative.parent).replace("\\", "/"), []).append(source)

    out = [HEADER]
    out.append(f"{len(sources())} sources, {len(groups)} directories.\n")

    for directory in sorted(groups):
        out.append(f"## {directory}\n")
        out.append("| Summary | What it is |")
        out.append("|---|---|")
        for source in groups[directory]:
            summary = source.with_name(source.name + ".md")
            link = summary.relative_to(ROOT).as_posix()
            out.append(f"| [`{summary.name}`]({relative_link(link)}) | {purpose_of(summary)} |")
        out.append("")

    return "\n".join(out).rstrip() + "\n"


def relative_link(path: str) -> str:
    """A path from docs/ to the file, which is where the index is read from."""
    return "../" + path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail when the committed index is out of date")
    args = parser.parse_args()

    rendered = render()

    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current == rendered:
            print("docs/source-summaries.md is up to date")
            return 0
        print("docs/source-summaries.md is out of date; run tools/generate-summary-index.py", file=sys.stderr)
        return 1

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(sources())} sources)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
