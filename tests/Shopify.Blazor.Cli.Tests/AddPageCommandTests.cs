using Shopify.Blazor.Cli.Commands;
using Xunit;

namespace Shopify.Blazor.Cli.Tests;

/// <summary>
/// Tests for <c>add page</c> and the template it writes.
/// </summary>
/// <remarks>
/// Every assertion here maps to a failure that produces no error message at all: a page without a
/// render mode renders and does nothing, a page without an empty state shows stale content, and an
/// overwrite without <c>--force</c> destroys work that was not in version control.
/// </remarks>
public sealed class AddPageCommandTests
{
    [Fact]
    public void The_generated_page_declares_one_click_handler_overload()
    {
        // Two LoadAsync overloads make OnClick="LoadAsync" ambiguous between Func<Task> and
        // Func<T, Task>, which is a compile error in every page this command writes. This test was
        // added after exactly that shipped: the page was compiled by hand against Polaris.Blazor
        // and Shopify.Blazor to find it.
        var content = PageTemplate.Render("Products");

        Assert.Contains("OnClick=\"LoadAsync\"", content);
        Assert.Equal(1, CountOccurrences(content, "private async Task LoadAsync("));
        Assert.Contains("await ReloadAsync();", content);
    }

    [Fact]
    public void The_generated_page_is_ordinary_razor_without_generated_file_markers()
    {
        // The output has to stay a file a developer can edit freely: no generated-code banner and
        // no do-not-edit marker, because the template's promise is an ordinary editable project.
        var content = PageTemplate.Render("Products");

        Assert.StartsWith("@page \"/products\"", content);
        Assert.Contains("PolarisPage", content);
        Assert.Contains("PolarisEmptyState", content);
        Assert.Contains("PolarisSection", content);
        Assert.DoesNotContain("<auto-generated", content);
        Assert.DoesNotContain("DO NOT EDIT", content);

        // AGENTS.md #21: a template renames the root namespace, so enclosing-namespace lookup stops
        // working and a type the page uses has to be imported explicitly. The page names
        // PolarisEventArgs and IAppBridgeInterop, so it imports both namespaces itself.
        Assert.Contains("@using Polaris.Blazor.Events", content);
        Assert.Contains("@using Shopify.Blazor.AppBridge", content);
    }

    private static int CountOccurrences(string haystack, string needle)
    {
        var count = 0;

        for (var index = haystack.IndexOf(needle, StringComparison.Ordinal);
             index >= 0;
             index = haystack.IndexOf(needle, index + needle.Length, StringComparison.Ordinal))
        {
            count++;
        }

        return count;
    }

    private static AddPageCommand Command(TempProject project) =>
        new(project.FileSystem, project.Environment, project.Console);

    private static int Run(TempProject project, params string[] args)
    {
        var parsed = ArgumentParser.Parse(args, AddPageCommand.AcceptedOptions);
        Assert.True(parsed.Succeeded, parsed.Error);

        return Command(project).Run(parsed.Arguments!, project.Root);
    }

    [Fact]
    public void Writes_a_page_with_the_render_mode_and_all_three_states()
    {
        // The whole point of the command: without @rendermode the page renders and every handler is
        // never attached (AGENTS.md #2); without the three states a failure or an empty result is
        // invisible. Neither throws.
        using var project = new TempProject()
            .WithHealthyProjectFile()
            .WithGlobalJson();

        var exitCode = Run(project, "Products");

        Assert.Equal(ExitCodes.Success, exitCode);
        Assert.True(project.Exists("Components/Pages/Products.razor"));

        var content = project.Read("Components/Pages/Products.razor");

        Assert.Contains("@page \"/products\"", content);
        Assert.Contains(PageTemplate.RenderModeDirective, content);
        Assert.Contains("<PolarisSpinner", content);
        Assert.Contains("_loading", content);
        Assert.Contains("<PolarisEmptyState", content);
        Assert.Contains("<PolarisBanner", content);
        Assert.Contains("<PolarisPage", content);
        Assert.Contains("<PolarisSection", content);
    }

    [Theory]
    [InlineData("Products", "/products")]
    [InlineData("ProductEditor", "/product-editor")]
    [InlineData("APIKeys", "/api-keys")]
    [InlineData("orderHistory", "/order-history")]
    public void Derives_a_kebab_case_route(string name, string expected)
    {
        // A route spelled differently from the name is a 404 at runtime, or a route that silently
        // shadows another page's.
        Assert.Equal(expected, PageTemplate.Route(name));
    }

    [Fact]
    public void Refuses_to_overwrite_an_existing_page_without_force()
    {
        // The command's central promise. A silent overwrite here loses work that may never have
        // been committed.
        using var project = new TempProject().WithHealthyProjectFile();

        project.Write("Components/Pages/Products.razor", "@* hand-written, must survive *@");

        var exitCode = Run(project, "Products");

        Assert.Equal(ExitCodes.AlreadyExists, exitCode);
        Assert.Equal("@* hand-written, must survive *@", project.Read("Components/Pages/Products.razor"));
        Assert.Contains("already exists", project.Console.Text);
        Assert.Contains("Nothing was written", project.Console.Text);
    }

    [Fact]
    public void Force_overwrites_and_reports_it()
    {
        // --force has to actually work, or the only way out of a refusal is to delete the file by
        // hand.
        using var project = new TempProject().WithHealthyProjectFile();

        project.Write("Components/Pages/Products.razor", "@* replaced *@");

        var exitCode = Run(project, "Products", "--force");

        Assert.Equal(ExitCodes.Success, exitCode);

        var content = project.Read("Components/Pages/Products.razor");

        Assert.DoesNotContain("replaced", content);
        Assert.Contains("@page \"/products\"", content);
    }

    [Fact]
    public void Dry_run_writes_nothing()
    {
        // A --dry-run that writes is worse than no dry run: it is a rehearsal the developer trusts
        // before pointing the command at a real project.
        using var project = new TempProject().WithHealthyProjectFile();

        var exitCode = Run(project, "Products", "--dry-run");

        Assert.Equal(ExitCodes.Success, exitCode);
        Assert.False(project.Exists("Components/Pages/Products.razor"));
        Assert.Contains("would create", project.Console.Text);
        Assert.Contains(Path.Combine("Components", "Pages", "Products.razor"), project.Console.Text);
    }

    [Fact]
    public void Dry_run_still_refuses_an_existing_file()
    {
        // A dry run that reports success and then fails for real teaches the developer to distrust
        // the one command whose job is to tell them what will happen.
        using var project = new TempProject().WithHealthyProjectFile();

        project.Write("Components/Pages/Products.razor", "@* keep *@");

        var exitCode = Run(project, "Products", "--dry-run");

        Assert.Equal(ExitCodes.AlreadyExists, exitCode);
        Assert.Equal("@* keep *@", project.Read("Components/Pages/Products.razor"));
    }

    [Fact]
    public void Writes_into_an_explicit_path_directory()
    {
        // --path is how a page goes into a feature folder instead of the default Pages directory,
        // and the project has to be discovered from there rather than from the cwd.
        using var project = new TempProject().WithHealthyProjectFile();
        var target = project.At("Components", "Pages", "Admin");

        var exitCode = Run(project, "Products", "--path", target);

        Assert.Equal(ExitCodes.Success, exitCode);
        Assert.True(project.Exists("Components/Pages/Admin/Products.razor"));
        Assert.False(project.Exists("Components/Pages/Products.razor"));
    }

    [Fact]
    public void Nav_inserts_an_entry_above_the_divider()
    {
        // The layout's navigation group is above the divider. An entry appended after it lands
        // outside the page chrome, which looks like the option did nothing.
        using var project = new TempProject().WithHealthyProjectFile().WithLayout();

        var exitCode = Run(project, "Products", "--nav");

        Assert.Equal(ExitCodes.Success, exitCode);

        var layout = project.Read("Components/Layout/MainLayout.razor");

        Assert.Contains("Href=\"/products\"", layout);
        Assert.True(
            layout.IndexOf("Href=\"/products\"", StringComparison.Ordinal)
                < layout.IndexOf("<PolarisDivider", StringComparison.Ordinal),
            "the navigation entry must come before the divider");
    }

    [Fact]
    public void Nav_succeeds_with_a_message_when_there_is_no_navigation_file()
    {
        // The spec is explicit: say so and succeed, rather than guessing where navigation lives and
        // corrupting a layout.
        using var project = new TempProject().WithHealthyProjectFile();

        var exitCode = Run(project, "Products", "--nav");

        Assert.Equal(ExitCodes.Success, exitCode);
        Assert.True(project.Exists("Components/Pages/Products.razor"));
        Assert.Contains("No navigation file found", project.Console.Text);
    }

    [Fact]
    public void Nav_is_idempotent()
    {
        // Running add page --nav twice must not produce two links to the same route.
        using var project = new TempProject().WithHealthyProjectFile().WithLayout();

        Run(project, "Products", "--nav");
        Run(project, "Products", "--nav", "--force");

        var layout = project.Read("Components/Layout/MainLayout.razor");
        var occurrences = layout.Split("Href=\"/products\"").Length - 1;

        Assert.Equal(1, occurrences);
    }

    [Fact]
    public void Rejects_a_name_that_cannot_be_a_component()
    {
        // Writing 'My Page.razor', or a page whose name has no letters to become a type name, is a
        // build error the developer did not ask for.
        using var project = new TempProject().WithHealthyProjectFile();

        var exitCode = Run(project, "///");

        Assert.Equal(ExitCodes.Usage, exitCode);
        Assert.Contains("cannot become a component name", project.Console.Text);
    }

    [Fact]
    public void Fails_clearly_when_there_is_no_project()
    {
        // Without this, the page is written to a directory nothing compiles, and the developer sees
        // a success message for a file that will never be part of the app.
        using var project = new TempProject();

        var exitCode = Run(project, "Products");

        Assert.Equal(ExitCodes.Usage, exitCode);
        Assert.Contains("No .csproj file", project.Console.Text);
    }
}
